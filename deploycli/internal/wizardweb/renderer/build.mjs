import {build} from "esbuild";
import {copyFile, mkdir} from "node:fs/promises";
import {fileURLToPath} from "node:url";
const root = fileURLToPath(new URL(".", import.meta.url));
await mkdir(new URL("../../../../internal/reportui/vendor/", import.meta.url), {recursive:true});
await build({
  absWorkingDir:root, entryPoints:["entry.mjs"],
  outfile:"../../../../internal/reportui/vendor/topology-three.js", bundle:true, minify:true,
  format:"iife", globalName:"WizardTopologyThree", target:["es2020"],
  legalComments:"eof", banner:{js:"// Generated by renderer/build.mjs. Three.js is licensed under MIT; see three-LICENSE.txt."}
});
await copyFile(new URL("node_modules/three/LICENSE", import.meta.url),
  new URL("../../../../internal/reportui/vendor/three-LICENSE.txt", import.meta.url));
